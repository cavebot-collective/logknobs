#!/usr/bin/env python3
"""Generate the simulator's display-width table from Unicode data.

A hand-picked range list missed U+1F680 (ROCKET) and produced 107 held-out
truncation failures two layers away from the actual defect. Generated tables
do not have that failure mode. probe_widths.py verifies git agrees with this
data on every codepoint the corpora contain -- and at last check it did on all
65 -- so Unicode EAW is used as git's table by proxy, with the proxy checked."""
import unicodedata, sys, pathlib
print(f"unicode data version: {unicodedata.unidata_version}", file=sys.stderr)
def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if pred(cp):
            if start is None: start = cp
        elif start is not None:
            out.append((start, cp-1)); start = None
    if start is not None: out.append((start, 0x10FFFF))
    return out
wide = ranges(lambda cp: unicodedata.east_asian_width(chr(cp)) in ("W","F"))
zero = ranges(lambda cp: unicodedata.category(chr(cp)) in ("Mn","Me","Cf") and cp not in (0x00AD,))
fmt = lambda rs: ",".join(f"[0x{a:X},0x{b:X}]" for a,b in rs)
out = pathlib.Path(sys.argv[1])
out.write_text(f"""// GENERATED by gen_width_table.py from Unicode {unicodedata.unidata_version}. Do not edit.
// Validated against git by probe_widths.py on every non-ASCII codepoint in the corpora.
export const WIDE_RANGES = [{fmt(wide)}];
export const ZERO_RANGES = [{fmt(zero)}];
""")
print(f"wide ranges: {len(wide)}, zero-width ranges: {len(zero)} -> {out}")
